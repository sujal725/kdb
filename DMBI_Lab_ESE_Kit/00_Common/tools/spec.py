import re


def slug(h):
    s = re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', h)
    return re.sub(r'[^A-Za-z0-9]+', '_', s).strip('_').lower()


def C(h, k, d, n=None, f=None, use=True):
    """column: h=csv header, k=kind (s,i,bi,d,f,date,time,yn), d=description"""
    return dict(h=h, k=k, d=d, n=n, f=f or slug(h), use=use)


def case(col, bounds, labels):
    parts = ["WHEN s.`%s` < %s THEN '%s'" % (col, b, l) for b, l in zip(bounds, labels)]
    return "CASE " + " ".join(parts) + " ELSE '%s' END" % labels[-1]


def AG(col):
    return case(col, [25, 35, 45, 55], ['18-24', '25-34', '35-44', '45-54', '55+'])


